// create a constructor class inside it i will define the behaviors(Methods) that a calculator should have(e.g) add, subtract multiply divide
public class Calculator {

    // constructor
    public Calculator() {
        // nothing here
    }

    // define public methods
    public int addition(int a, int b) {
        return a + b;
    }

    public int subtraction(int a, int b) {
        return a - b;
    }

    public int multiplication(int a, int b) {
        return a * b;
    }

    public int division(int a, int b) {
        return a / b;
    }

}
